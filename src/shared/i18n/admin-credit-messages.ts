export const CREDIT_DICTIONARIES: Record<LocaleCode, AdminCreditMessages> = { th, en, "zh-CN": zhCN };

export function getCreditMessages(code: LocaleCode): AdminCreditMessages {
  return CREDIT_DICTIONARIES[code] ?? th;
}

export function fill(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, k: string) => (k in values ? String(values[k]) : `{${k}}`));
}

